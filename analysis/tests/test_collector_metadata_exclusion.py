sys.path.insert(0, str(Path(__file__).parent.parent))

from analyzers.static.analyzer import COLLECTOR_METADATA_FILES, StaticAnalyzer


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def write_files(root: Path, files: dict[str, str]) -> None:
    for relative, content in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")


def make_detail_json(**extra) -> str:
    payload = {
        "id": "test-skill",
        "name": "Test Skill",
        "description": "A skill that uses token authentication and https://marketplace.example.com",
        "publisher": "example-publisher",
        "authorization": "bearer secret_key_here",
        **extra,
    }
    return json.dumps(payload)


