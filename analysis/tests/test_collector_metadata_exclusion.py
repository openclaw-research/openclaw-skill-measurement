def test_skill_card_md_appears_in_collector_metadata_files():
    """skill-card.md is auto-generated by ClawScan and must be routed to
    collector_metadata_files, not the scanned file inventory."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "SKILL.md": "# My Skill\nBenign description.",
            "skill-card.md": (
                "# Auto-generated Skill Card\n"
                "This card was created by ClawScan and describes the skill.\n"
                "- [Content System prompt](artifact/prompts/prompt3.md)"
            ),
        })
        report = StaticAnalyzer().analyze(root)

    skill_paths = {f["path"] for f in report.result_json["file_inventory"]}
    collector_paths = {f["path"] for f in report.result_json["collector_metadata_files"]}

    assert "skill-card.md" not in skill_paths, \
        "skill-card.md must not appear in file_inventory"
    assert "skill-card.md" in collector_paths, \
        "skill-card.md must appear in collector_metadata_files"

def test_skill_card_md_content_does_not_elevate_risk_level():
    """A benign SKILL.md alongside an auto-generated skill-card.md containing
    prose like 'system prompt' must not elevate risk_level. This was the
    root cause of skill_id=3208 being rated 'high' in run #70 before the
    skill-card.md exclusion was added."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "SKILL.md": "# My Skill\nBenign description with no risky patterns.",
            "skill-card.md": (
                "- [Content Marketing System prompt](artifact/prompts/prompt3.md)\n"
                "- Mentions token, secret, authorization in descriptive prose.\n"
            ),
        })
        report = StaticAnalyzer().analyze(root)

    assert report.risk_level == "none", (
        f"risk_level should be 'none' (skill-card.md must be excluded from "
        f"content analysis); got {report.risk_level!r}"
    )


def test_detail_json_urls_do_not_appear_in_external_urls():
    detail_with_url = make_detail_json(homepage="https://metadata-only.example.com/skill")
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "SKILL.md": "# My Skill",
            "_detail.json": detail_with_url,
        })
        report = StaticAnalyzer().analyze(root)

    domains = report.result_json["external_urls"]["domains"]
    assert "metadata-only.example.com" not in domains, (
        "Domains from _detail.json must not appear in external_urls"
    )


def test_detail_json_secret_terms_do_not_trigger_secret_handling():
    """
    _detail.json often contains 'token', 'secret', 'authorization' in its schema.
    These must not inflate secret_handling indicators.
    """
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "SKILL.md": "# My Skill\nThis skill performs a useful task.",
            "_detail.json": make_detail_json(),  # contains token, secret, authorization
        })
        report = StaticAnalyzer().analyze(root)

    secret_count = report.result_json["indicators"]["secret_handling"]["count"]
    assert secret_count == 0, (
        f"secret_handling count should be 0, got {secret_count}; "
        "check that _detail.json is not being analyzed"
    )


