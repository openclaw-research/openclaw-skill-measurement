    """_detail.json nested inside a subdirectory must also be excluded."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "subdir/_detail.json": make_detail_json(),
            "main.py": "print('hello')\n",
        })
        report = StaticAnalyzer().analyze(root)

    skill_paths = {f["path"] for f in report.result_json["file_inventory"]}
    collector_paths = {f["path"] for f in report.result_json["collector_metadata_files"]}
    assert "subdir/_detail.json" not in skill_paths
    assert "subdir/_detail.json" in collector_paths
