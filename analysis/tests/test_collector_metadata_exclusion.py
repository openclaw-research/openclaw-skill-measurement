def test_detail_json_not_in_skill_file_inventory():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_files(root, {
            "SKILL.md": "# My Skill\nThis skill does something useful.",
            "_detail.json": make_detail_json(),
        })
        report = StaticAnalyzer().analyze(root)

    skill_paths = {f["path"] for f in report.result_json["file_inventory"]}
    assert "_detail.json" not in skill_paths, "_detail.json must not appear in file_inventory"


